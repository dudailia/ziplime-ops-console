import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { parseDryRun } from "./parse";

const SAMPLE = readFileSync(new URL("./__fixtures__/sample_dry_run.jsonl", import.meta.url), "utf8");

const place = (over: Record<string, unknown> = {}) => ({
  account: "de***nt",
  broker_validated: true,
  client_order_id: "c1",
  dry_run_id: "dryrun-c1",
  event: "place",
  limit_price: null,
  order_dt: "2026-10-12T10:00:00-04:00",
  order_type: "market",
  quantity: "5",
  recorded_at: "2026-10-12T14:00:00.000100+00:00",
  requested_amount: 5.0,
  route: "auto",
  side: "buy",
  symbol: "AAPL",
  time_in_force: "day",
  ziplime_order_id: "o1",
  ...over,
});

const jsonl = (...records: unknown[]) => records.map((r) => JSON.stringify(r)).join("\n") + "\n";

describe("parseDryRun on the real sample (generated by the engine)", () => {
  const parsed = parseDryRun(SAMPLE, "sample_dry_run.jsonl");

  it("loads every line with no errors or warnings", () => {
    expect(parsed.errors).toEqual([]);
    expect(parsed.warnings).toEqual([]);
    expect(parsed.events).toHaveLength(13);
  });

  it("counts each event kind", () => {
    expect(parsed.sessions).toHaveLength(1);
    const [session] = parsed.sessions;
    expect(session.date).toBe("2026-10-12");
    expect(session.counts).toEqual({ place: 5, refuse: 5, skip: 2, cancel: 1 });
    expect(session.refusalRate).toBe(0.5);
  });

  it("keeps the engine's types: quantity and limit price as strings, amount as a number", () => {
    const first = parsed.events[0];
    expect(first.event).toBe("place");
    if (first.event !== "place") return;
    expect(first.quantity).toBe("40");
    expect(first.limit_price).toBe("571.2");
    expect(first.requested_amount).toBe(40);
    expect(first.broker_validated).toBe(true);
    expect(first.clock).toEqual({ session: "2026-10-12", minuteET: 9 * 60 + 31, source: "order_dt" });
  });

  it("reads refusals and skips with their reasons and signed amounts", () => {
    const sell = parsed.events.find((e) => e.event === "refuse" && e.ziplime_order_id === "sess1-007");
    expect(sell).toMatchObject({
      symbol: "AAPL",
      requested_amount: -20,
      reason: "ValueError: Lime sell orders are disabled by the configured risk limits",
    });
    const skip = parsed.events.find((e) => e.event === "skip" && e.ziplime_order_id === "sess1-003");
    expect(skip).toMatchObject({ requested_amount: 0.6, symbol: "NVDA" });
  });

  it("places a cancel by recorded_at, in the session of the order it cancels", () => {
    const cancel = parsed.events.find((e) => e.event === "cancel");
    expect(cancel).toMatchObject({ dry_run_id: "dryrun-sess1006a4af23e310", known_order: true, symbol: "NVDA" });
    expect(cancel?.clock.source).toBe("recorded_at");
    expect(cancel?.clock.session).toBe("2026-10-12");
  });

  it("collects the masked account ids", () => {
    expect(parsed.accounts).toEqual(["de***nt"]);
  });
});

describe("parseDryRun defensively", () => {
  it("reports a malformed line by number and still loads the rest", () => {
    const lines = [
      JSON.stringify(place({ ziplime_order_id: "a" })),
      JSON.stringify(place({ ziplime_order_id: "b", dry_run_id: "dryrun-b" })),
      '{"event": "place", "symbol": "AAPL"',
      JSON.stringify(place({ ziplime_order_id: "d", dry_run_id: "dryrun-d" })),
      JSON.stringify(place({ ziplime_order_id: "e", dry_run_id: "dryrun-e" })),
    ];
    const parsed = parseDryRun(lines.join("\n") + "\n", "f");
    expect(parsed.events.map((e) => e.line)).toEqual([1, 2, 4, 5]);
    expect(parsed.errors).toHaveLength(1);
    expect(parsed.errors[0].line).toBe(3);
    expect(parsed.errors[0].message).toMatch(/Not valid JSON/);
    expect(parsed.errors[0].raw).toBe('{"event": "place", "symbol": "AAPL"');
  });

  it("names every missing or mistyped field", () => {
    const bad = place({ quantity: 5, side: "short" }) as Record<string, unknown>;
    delete bad.symbol;
    const parsed = parseDryRun(jsonl(bad), "f");
    expect(parsed.events).toEqual([]);
    const { message } = parsed.errors[0];
    expect(message).toContain('missing "symbol"');
    expect(message).toContain('"quantity" must be a string, got number');
    expect(message).toContain('"side" must be one of buy, sell');
  });

  it("rejects an unknown event, a missing event and a non-object line", () => {
    const parsed = parseDryRun(jsonl({ event: "fill", recorded_at: "x" }, { symbol: "AAPL" }, [1, 2], 42), "f");
    expect(parsed.errors.map((e) => e.message)).toEqual([
      'Unknown event "fill" (expected place, refuse, skip or cancel)',
      'Missing "event"',
      "Expected a JSON object, got array",
      "Expected a JSON object, got number",
    ]);
  });

  it("rejects a timestamp without a timezone offset", () => {
    const parsed = parseDryRun(jsonl(place({ order_dt: "2026-10-12T10:00:00" })), "f");
    expect(parsed.errors[0].message).toMatch(/"order_dt" must be an ISO timestamp with a timezone offset/);
  });

  it("accepts a null order_dt and falls back to recorded_at", () => {
    const parsed = parseDryRun(jsonl(place({ order_dt: null })), "f");
    expect(parsed.errors).toEqual([]);
    expect(parsed.events[0].clock).toEqual({ session: "2026-10-12", minuteET: 10 * 60, source: "recorded_at" });
  });

  it("keeps fields it doesn't know about", () => {
    const parsed = parseDryRun(jsonl(place({ strategy_version: "2.1" })), "f");
    expect(parsed.events[0].extra).toEqual({ strategy_version: "2.1" });
  });

  it("handles CRLF, blank lines and a byte-order mark", () => {
    const text = "﻿" + JSON.stringify(place()) + "\r\n\r\n" + JSON.stringify(place({ dry_run_id: "dryrun-2" })) + "\r\n";
    const parsed = parseDryRun(text, "f");
    expect(parsed.errors).toEqual([]);
    expect(parsed.events.map((e) => e.line)).toEqual([1, 3]);
    expect(parsed.events[0].raw.endsWith("\r")).toBe(false);
  });

  it("returns an empty result for an empty file", () => {
    const parsed = parseDryRun("", "f");
    expect(parsed).toMatchObject({ events: [], errors: [], warnings: [], sessions: [], accounts: [] });
  });

  it("warns when the last line has no newline, and still parses it", () => {
    const parsed = parseDryRun(JSON.stringify(place()), "f");
    expect(parsed.events).toHaveLength(1);
    expect(parsed.warnings[0]).toMatch(/Line 1 has no trailing newline/);
  });

  it("warns about a dry_run_id placed twice", () => {
    const parsed = parseDryRun(jsonl(place(), place({ ziplime_order_id: "o2" })), "f");
    expect(parsed.events).toHaveLength(2);
    expect(parsed.warnings[0]).toMatch(/Line 2: dry_run_id dryrun-c1 was already placed/);
  });

  it("keeps a null account out of the account list", () => {
    const parsed = parseDryRun(jsonl(place({ account: null })), "f");
    expect(parsed.errors).toEqual([]);
    expect(parsed.accounts).toEqual([]);
  });
});

describe("parseDryRun on the trading clock", () => {
  it("files a cancel written the next day under the session of its order", () => {
    const cancel = {
      account: "de***nt",
      dry_run_id: "dryrun-c1",
      event: "cancel",
      known_order: true,
      recorded_at: "2026-10-13T13:35:00+00:00",
      symbol: "AAPL",
    };
    const parsed = parseDryRun(jsonl(place(), cancel), "f");
    expect(parsed.sessions.map((s) => s.date)).toEqual(["2026-10-12"]);
    expect(parsed.events[1].clock).toEqual({ session: "2026-10-12", minuteET: 9 * 60 + 35, source: "recorded_at" });
  });

  it("files a cancel of an unknown order by its own ET date", () => {
    const cancel = {
      account: "de***nt",
      dry_run_id: "some-live-broker-order",
      event: "cancel",
      known_order: false,
      recorded_at: "2026-10-14T15:00:00+00:00",
      symbol: null,
    };
    const parsed = parseDryRun(jsonl(cancel), "f");
    expect(parsed.events[0].clock.session).toBe("2026-10-14");
    expect(parsed.events[0].clock.minuteET).toBe(11 * 60);
  });

  it("uses the ET date, not the UTC date, near midnight", () => {
    const parsed = parseDryRun(jsonl(place({ order_dt: "2026-10-13T02:00:00+00:00" })), "f");
    expect(parsed.events[0].clock.session).toBe("2026-10-12");
    expect(parsed.events[0].clock.minuteET).toBe(22 * 60);
  });

  it("handles both sides of the November DST change", () => {
    const parsed = parseDryRun(
      jsonl(
        place({ order_dt: "2026-10-30T09:31:00-04:00", dry_run_id: "dryrun-a" }),
        place({ order_dt: "2026-11-02T09:31:00-05:00", dry_run_id: "dryrun-b" }),
        place({ order_dt: "2026-11-02T14:45:00+00:00", dry_run_id: "dryrun-c" }),
      ),
      "f",
    );
    expect(parsed.events.map((e) => [e.clock.session, e.clock.minuteET])).toEqual([
      ["2026-10-30", 571],
      ["2026-11-02", 571],
      ["2026-11-02", 9 * 60 + 45],
    ]);
  });

  it("sorts each session's events by clock time, then by line", () => {
    const parsed = parseDryRun(
      jsonl(
        place({ order_dt: "2026-10-12T11:00:00-04:00", dry_run_id: "dryrun-a" }),
        place({ order_dt: "2026-10-12T10:00:00-04:00", dry_run_id: "dryrun-b" }),
        place({ order_dt: "2026-10-12T10:00:00-04:00", dry_run_id: "dryrun-c" }),
      ),
      "f",
    );
    expect(parsed.sessions[0].events.map((e) => e.line)).toEqual([2, 3, 1]);
  });
});
