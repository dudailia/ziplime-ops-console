import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import accountsFile from "../../data/seed/accounts.json";
import manifest from "../../data/seed/manifest.json";
import { maskAccountId } from "./dryrun/mask";
import { parseDryRun } from "./dryrun/parse";

const seedFile = (file: string) => readFileSync(new URL(`../../data/seed/${file}`, import.meta.url), "utf8");

describe("maskAccountId", () => {
  it("masks exactly like the engine", () => {
    expect(maskAccountId("demo-account")).toBe("de***nt"); // test_lime_dry_run.py
    expect(maskAccountId("LX-40217")).toBe("LX***17");
    expect(maskAccountId("abcd")).toBe("****");
  });
});

describe("seed data generated by the engine", () => {
  it("has 8 to 12 accounts, all on Beta", () => {
    expect(accountsFile.accounts.length).toBeGreaterThanOrEqual(8);
    expect(accountsFile.accounts.length).toBeLessThanOrEqual(12);
    expect(new Set(accountsFile.accounts.map((a) => a.plan))).toEqual(new Set(["beta"]));
  });

  it("gives every account at least one deployment", () => {
    const withDeployments = new Set(manifest.deployments.map((d) => d.account));
    expect(accountsFile.accounts.filter((a) => !withDeployments.has(a.id))).toEqual([]);
  });

  describe.each(manifest.deployments)("$id", (deployment) => {
    const parsed = parseDryRun(seedFile(deployment.file), deployment.id);
    const account = accountsFile.accounts.find((a) => a.id === deployment.account);

    it("parses with no errors or warnings", () => {
      expect(parsed.errors).toEqual([]);
      expect(parsed.warnings).toEqual([]);
      expect(parsed.events).toHaveLength(deployment.lines);
    });

    it("matches the manifest's counts and sessions", () => {
      const counts = { place: 0, refuse: 0, skip: 0, cancel: 0 };
      for (const s of parsed.sessions) for (const k of Object.keys(counts) as (keyof typeof counts)[]) counts[k] += s.counts[k];
      expect(counts).toEqual(deployment.counts);
      expect(parsed.sessions.map((s) => s.date)).toEqual(deployment.sessions);
    });

    it("carries the account's masked number on every line", () => {
      expect(account).toBeDefined();
      expect(parsed.accounts).toEqual([maskAccountId(account!.accountNumber)]);
    });

    it("keeps every event inside regular trading hours", () => {
      const outside = parsed.events.filter((e) => e.clock.minuteET < 9 * 60 + 30 || e.clock.minuteET >= 16 * 60);
      expect(outside.map((e) => e.line)).toEqual([]);
    });
  });
});

describe("seed module", () => {
  it("bundles exactly the deployments in the manifest, as text", async () => {
    const { RAW, seedFile } = await import("./seed");
    expect(Object.keys(RAW).sort()).toEqual(manifest.deployments.map((d) => d.id).sort());
    for (const d of manifest.deployments) expect(seedFile(d.id).events).toHaveLength(d.lines);
  });
});
